// Load EN dict once
const fullEnDict = JSON.parse(fs.readFileSync('D:/Projects/New-Halabja-Center-Website/tools/final_en_dict.json', 'utf8'));

let changes = 0;

data.categories.forEach(c => {
    if (c.members) {
        c.members.forEach(m => {
            if (m.name && m.name.ku) {
                let kuWords = m.name.ku.split(/\s+/);
                
                let newAr = kuWords.map(w => {
                    if(arOverrides[w]) return arOverrides[w];
                    
                    let ar = w;
                    // Intelligently clean Kurdish phonetics
                    
                    if (ar.startsWith("ئا")) ar = ar.replace("ئا", "آ");
                    else if (ar.startsWith("ئە")) ar = ar.replace("ئە", "أ");
                    else if (ar.startsWith("ئی")) ar = ar.replace("ئی", "إي");
                    else if (ar.startsWith("ئێ")) ar = ar.replace("ئێ", "إي");
                    else if (ar.startsWith("ئۆ") || ar.startsWith("ئو")) {
                        ar = ar.replace(/^ئ[ۆو]/, "أو");
                    }
                    else if (ar.startsWith("ئ")) ar = ar.replace("ئ", "أ");

                    ar = ar.replace(/ڕ/g, "ر").replace(/ڵ/g, "ل")
                           .replace(/ڤ/g, "ف").replace(/پ/g, "ب")
                           .replace(/چ/g, "ش").replace(/گ/g, "غ")
                           .replace(/ۆ/g, "و").replace(/ێ/g, "ي")
                           .replace(/ژ/g, "ج").replace(/وو/g, "و")
                           .replace(/ی/g, "ي");
                    
                    // Intelligent 'ە' handler!
                    // Middle 'ە' is removed (e.g. بەختیار -> بختيار)
                    // End 'ە' becomes 'ة' (e.g. تەرزە -> ترزة)
                    ar = ar.replace(/ە/g, (match, offset, str) => {
                        return offset === str.length - 1 ? 'ة' : '';
                    });
                    
                    return ar;
                }).join(' ').trim();
                
                let newEn = kuWords.map(w => {
                    if (enOverrides[w]) return enOverrides[w];
                    let en = fullEnDict[w];
                    if(en) {
                       en = en.replace(/ص/g, "s").replace(/غ/g, "gh").replace(/ط/g, "t").replace(/ض/g, "dh").replace(/ظ/g, "dh").replace(/ث/g, "th").replace(/ذ/g, "dh");
                    }
                    return en || w;
                }).join(' ').trim();
                
                if (m.name.ar !== newAr || m.name.en !== newEn) {
                   m.name.ar = newAr;
                   m.name.en = newEn;
                   changes++;
                }
            }
        });
    }
});

fs.writeFileSync(file, JSON.stringify(data, null, 2), 'utf8');
console.log(`Successfully reapplied perfect Arabic translations to ${changes} entries.`);

